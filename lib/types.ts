// Client-side shapes returned by the API.
export type EventView = {
  id: string;
  orgId: string;
  title: string;
  description: string;
  foodType: string;
  goodies: string;
  date: string;
  endDate: string | null;
  campus: string;
  format: string;
  virtualUrl: string | null;
  registrationUrl: string | null;
  visibility: string;
  restrictions: string[];
  coHosts: string[];
  agenda: { time: string; title: string; day?: string }[];
  waitlistEnabled: boolean;
  startTime: string;
  endTime: string;
  budget: number;
  capacity: number;
  venueId: string | null;
  location: string;
  websiteUrl: string | null;
  eventType: string;
  audience: string;
  ticketCost: number;
  tags: string[];
  accessibilityNotes: string;
  flyerHeadline: string;
  flyerTagline: string;
  flyerColor: string;
  flyerImageUrl: string | null;
  cardBlurb: string;
  status: string;
  createdAt: string;
  org?: { id: string; name: string; logoUrl: string; category: string } | null;
  venue?: { id: string; name: string; capacity: number; accessible: boolean; costPerHour: number } | null;
};
export type Friend = { id: string; name: string; avatarUrl: string };
export type RankedEventView = EventView & {
  score: number;
  why: string;
  friendsGoing: Friend[];
  conflict: { title: string } | null;
  conflicts: ConflictItem[];
  isNew: boolean;
  matchPct: number;
  rankPos: number;
  factors: Record<string, number>;
};
export type ConflictItem = { kind: string; title: string; when: string; eventId?: string };
export type ScheduleBlockView = { id: string; kind: string; source: string; title: string; location: string; day: number; start: string; end: string; editable: boolean };
export type FunnelView = {
  rightSwipes: number;
  leftSwipes: number;
  preRegistered: number;
  registered: number;
  checkedIn: number;
  capacity: number;
  avgRating: number;
  feedbackCount: number;
  reasons: Record<string, number>;
};
export type Theme = { theme: string; count: number; sentiment: "positive" | "neutral" | "negative"; quote: string };
export type RecordView = {
  id: string;
  eventId: string;
  markdown: string;
  stats: Record<string, unknown>;
  feedbackThemes: Theme[];
  swipeInsights: Record<string, number>;
  keepChange: { keep: string[]; change: string[] };
  approved: boolean;
  createdAt: string;
};
export type StudentLite = { id: string; name: string; email?: string | null; avatarUrl: string; major: string; year: string; onboarded: boolean };
export type OrgLite = { id: string; name: string; logoUrl: string; category: string };
